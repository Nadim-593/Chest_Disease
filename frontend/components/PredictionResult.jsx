"use client";

import { useEffect, useState } from "react";
import {
  CheckCircle,
  AlertCircle,
  Clock,
  Cpu,
  Info,
} from "lucide-react";
import ConfidenceBar from "@/components/ConfidenceBar";

const PREDICTION_COLORS = {
  NORMAL: {
    badge: "bg-emerald-100 text-emerald-800 border-emerald-200",
    icon: "text-emerald-500",
    bar: "from-emerald-400 to-emerald-600",
  },
  PNEUMONIA: {
    badge: "bg-red-100 text-red-800 border-red-200",
    icon: "text-red-500",
    bar: "from-red-400 to-red-600",
  },
};

function getPredictionStyle(prediction) {
  const upper = (prediction || "").toUpperCase();
  return PREDICTION_COLORS[upper] || {
    badge: "bg-sky-100 text-sky-800 border-sky-200",
    icon: "text-sky-500",
    bar: "from-sky-400 to-sky-600",
  };
}

export default function PredictionResult({ result, timestamp }) {
  const [visible, setVisible] = useState(false);

  useEffect(() => {
    if (result) {
      setVisible(false);
      const timer = setTimeout(() => setVisible(true), 50);
      return () => clearTimeout(timer);
    }
  }, [result]);

  if (!result) {
    return (
      <div className="flex flex-col items-center justify-center h-full min-h-48 text-center py-12 px-6">
        <div className="w-16 h-16 rounded-2xl bg-slate-100 flex items-center justify-center mb-4">
          <Cpu className="w-8 h-8 text-slate-300" aria-hidden="true" />
        </div>
        <p className="text-sm font-semibold text-slate-500">Ready for Analysis</p>
        <p className="text-xs text-slate-400 mt-1">
          Upload a chest X-ray to begin.
        </p>
      </div>
    );
  }

  const style = getPredictionStyle(result.prediction);
  const formattedConfidence = typeof result.confidence === "number"
    ? result.confidence.toFixed(2)
    : "—";

  return (
    <div
      className={`space-y-4 transition-all duration-500 ${
        visible ? "opacity-100 translate-y-0" : "opacity-0 translate-y-3"
      }`}
      role="region"
      aria-label="Analysis result"
      aria-live="polite"
    >
      {/* Status */}
      <div className="flex items-center gap-2">
        <CheckCircle className={`w-4 h-4 ${style.icon}`} aria-hidden="true" />
        <span className="text-sm font-semibold text-slate-700">Analysis Complete</span>
      </div>

      {/* Prediction badge */}
      <div className="p-5 bg-slate-50 border border-slate-200 rounded-xl">
        <p className="text-xs text-slate-400 uppercase tracking-wider mb-2">
          Prediction
        </p>
        <div className="flex items-center gap-3">
          <span
            className={`inline-block px-4 py-1.5 text-xl font-black rounded-lg border tracking-widest ${style.badge}`}
          >
            {result.prediction}
          </span>
        </div>
      </div>

      {/* Confidence */}
      <div className="p-5 bg-slate-50 border border-slate-200 rounded-xl">
        <div className="flex items-center justify-between mb-3">
          <p className="text-xs text-slate-400 uppercase tracking-wider">
            Confidence Score
          </p>
          <span className="text-xl font-bold text-slate-900">
            {formattedConfidence}%
          </span>
        </div>
        <ConfidenceBar
          confidence={result.confidence}
          colorClass={style.bar}
        />
        <p className="text-xs text-slate-400 mt-2">
          Model confidence in the predicted classification
        </p>
      </div>

      {/* Model info */}
      <div className="p-4 bg-slate-50 border border-slate-200 rounded-xl">
        <p className="text-xs text-slate-400 uppercase tracking-wider mb-3 flex items-center gap-1.5">
          <Info className="w-3.5 h-3.5" aria-hidden="true" />
          Analysis Details
        </p>
        <div className="grid grid-cols-2 gap-3">
          <div>
            <p className="text-xs text-slate-400">Model</p>
            <p className="text-sm font-medium text-slate-700">XRayAI v1.0</p>
          </div>
          <div>
            <p className="text-xs text-slate-400">Status</p>
            <p className="text-sm font-medium text-emerald-600">Completed</p>
          </div>
        </div>
      </div>

      {/* Timestamp */}
      {timestamp && (
        <div className="flex items-center gap-2 text-xs text-slate-400">
          <Clock className="w-3.5 h-3.5" aria-hidden="true" />
          <span>Analyzed at {timestamp}</span>
        </div>
      )}

      {/* Result disclaimer */}
      <div className="flex items-start gap-2 p-3 bg-amber-50 border border-amber-200 rounded-lg">
        <AlertCircle className="w-4 h-4 text-amber-500 flex-shrink-0 mt-0.5" aria-hidden="true" />
        <p className="text-xs text-amber-700">
          This result is generated by an AI model for research purposes only. It is not a medical diagnosis.
        </p>
      </div>
    </div>
  );
}
